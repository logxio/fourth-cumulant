"""Print the table colors as LaTeX \\definecolor lines, derived from palette.py (the one color source).

tables.lua runs this at build time, so a palette change reaches every table. Six role families are derived
from palette.py's four base hues (blue, iris, gold, gray):
- blue   (headline & K=4 scaling)
- iris   (official scorer receipts, chain B)
- slate  (ablation tables: equal-lightness blend of blue and iris)
- gold   (cost & budget ledgers)
- stone  (dead ends: equal-lightness warm stone blend of gray and gold)
- gray   (appendix reference tables)
Per family: line (middle-tone rules), mid, fill (header band), wash (summary and reference rows),
washz (column wash on a shaded row), zebra (very pale same-hue alternating row shading), and text
(subscript intervals and tag lettering).
"""
import palette as P


def _quad(stroke, fill):
    return (stroke, P.mix(stroke, fill, .45), fill, P.mix(fill, '#FFFFFF', .48))


def families():
    fams = dict(P.HUES)
    b_s, _, b_f, _ = P.HUES['blue']
    i_s, _, i_f, _ = P.HUES['iris']
    fams['slate'] = _quad(P.mix(b_s, i_s, .52), P.mix(b_f, i_f, .52))
    gr_s, _, gr_f, _ = P.HUES['gray']
    go_s, _, go_f, _ = P.HUES['gold']
    fams['stone'] = _quad(P.mix(gr_s, go_s, .28), P.mix(gr_f, go_f, .28))
    return fams


def tones(quad):
    stroke, mid, fill, wash = quad
    return {
        'line': stroke,
        'mid': mid,
        'fill': fill,
        'wash': wash,
        'washz': P.mix(wash, fill, .55),
        'zebra': P.mix(fill, '#FFFFFF', .78),
        'text': P.mix(stroke, P.INK, .42),
    }


def main():
    out = ['% generated by report/table_colors.py from report/palette.py; do not edit']
    for name, quad in families().items():
        for tone, hexval in tones(quad).items():
            out.append(r'\definecolor{tb%s%s}{HTML}{%s}' % (name, tone, hexval.lstrip('#').upper()))
    out.append(r'\definecolor{tbzebra}{HTML}{%s}' % P.mix(P.HUES['gray'][2], '#FFFFFF', .22).lstrip('#').upper())
    out.append(r'\definecolor{tbink}{HTML}{%s}' % P.INK.lstrip('#').upper())
    out.append(r'\definecolor{tbmuted}{HTML}{%s}' % P.MUTED.lstrip('#').upper())
    print('\n'.join(out))


if __name__ == '__main__':
    main()
