--[[ tables.lua: house style for every pipe table of the report (pandoc -> LaTeX).

A table is named by the paragraph right before it ("**Table 4.** ..." -> "4", "**One claim, ...**" -> "summary")
or by its section heading (dead ends). SPEC gives each name a role; the role fixes the hue of the rules, the header
band, the same-hue whisper zebra, and the cel caption mark, while the emphasis layers below are shared across roles.
A table missing from SPEC gets the reference style, and a SPEC entry whose table is gone is skipped, so moving or
merging tables needs no edit here.
Colors are defined at build time by table_colors.py from palette.py; the LaTeX macros live in pdf_header.tex.
]]

