local stringify = pandoc.utils.stringify
local STYLE_MODE = os.getenv('TABLES_STYLE') or 'C'

local function starts(s, prefix) return s:sub(1, #prefix) == prefix end

local function first_match(list, s)
  for _, item in ipairs(list or {}) do
    local p = type(item) == 'table' and item[1] or item
    if starts(s, p) then return item end
  end
end

local function latex(inlines)
  local s = pandoc.write(pandoc.Pandoc({ pandoc.Plain(inlines) }), 'latex', { wrap_text = 'wrap-none' })
  return (s:gsub('%s+$', ''))
end

-- A cell reads as a number when it has a digit and few letters (sci-notation e and units like "s" aside).
local function numeric(text)
  if text == '' or not text:find('%d') then return false end
  local t = text:gsub('(%d)e([%-−]?%d)', '%1%2')
  local letters = select(2, t:gsub('%a', ''))
  return letters / (utf8.len(t) or #t) <= 0.3
end

-- The bold face (STIXGeneral-Bold) has no Unicode super- and subscript digits: in bold text, set them with
-- \textsuperscript and \textsubscript.
local SUP = { [0x2070] = '0', [0xB9] = '1', [0xB2] = '2', [0xB3] = '3', [0x2074] = '4', [0x2075] = '5', [0x2076] = '6',
  [0x2077] = '7', [0x2078] = '8', [0x2079] = '9', [0x207A] = '+', [0x207B] = '−' }
local SUB = {}
for k = 0, 9 do SUB[0x2080 + k] = tostring(k) end

local function scripts(inlines)
  local out = pandoc.List()
  for _, el in ipairs(inlines) do
    if el.t == 'Str' and (el.text:find('[\xC2\xE2]')) then
      local buf, kind, run = '', nil, ''
      local function flush_run()
        if kind then
          out:insert(pandoc.RawInline('latex', '\\text' .. kind .. 'script{' .. run .. '}'))
          kind, run = nil, ''
        end
      end
      for _, cp in utf8.codes(el.text) do
        local k = SUP[cp] and 'super' or (SUB[cp] and 'sub') or nil
        if k then
          if buf ~= '' then out:insert(pandoc.Str(buf)); buf = '' end
          if kind ~= k then flush_run() end
          kind, run = k, run .. (SUP[cp] or SUB[cp])
        else
          flush_run()
          buf = buf .. utf8.char(cp)
        end
      end
      flush_run()
      if buf ~= '' then out:insert(pandoc.Str(buf)) end
    elseif el.t == 'Strong' or el.t == 'Emph' or el.t == 'Link' then
      el.content = scripts(el.content)
      out:insert(el)
    else
      out:insert(el)
    end
  end
  return out
end

-- scripts() inside every Strong of a body cell
local function bold_scripts(inlines)
  local out = pandoc.List()
  for _, el in ipairs(inlines) do
    if el.t == 'Strong' then el.content = scripts(el.content) end
    out:insert(el)
  end
  return out
end

-- Wrap numeric bracketed or parenthesized spans ("[0.813, 0.830]", "(1.06–1.13)", "(net 0)", "(earlier order scan)")
-- as small tinted subscripts/annotations.
local function intervals(inlines, color)
  local out = pandoc.List()
  local i = 1
  while i <= #inlines do
    local el = inlines[i]
    if el.t == 'Strong' or el.t == 'Emph' then
      el.content = intervals(el.content, color)
      out:insert(el)
      i = i + 1
    elseif el.t == 'Str' and (starts(el.text, '[') or starts(el.text, '(')) then
      local close = starts(el.text, '[') and ']' or ')'
      local j, text = i, ''
      while j <= #inlines and j < i + 8 do
        local e = inlines[j]
        if e.t == 'Str' then text = text .. e.text elseif e.t == 'Space' then text = text .. ' ' else break end
        if e.t == 'Str' and e.text:sub(-#close) == close then break end
        j = j + 1
      end
      local body = text:sub(2, -2)
      local is_num_ivl = body:find('%d') and not body:find('%a%a%a%a')
      local is_trailing_note = (i > 1 and j == #inlines and text:sub(-1) == close and #body <= 22)
      if j <= #inlines and text:sub(-1) == close and (is_num_ivl or is_trailing_note) then
        out:insert(pandoc.RawInline('latex', '\\tbivl{tb' .. color .. 'text}{'))
        for k = i, j do out:insert(inlines[k]) end
        out:insert(pandoc.RawInline('latex', '}'))
        i = j + 1
      else
        out:insert(el)
        i = i + 1
      end
    else
      out:insert(el)
      i = i + 1
    end
  end
  return out
end

-- Wrap bracketed comparison clauses [...] in prose columns (e.g. Table A3's [#335351] baseline notes)
-- in line-breakable smaller tinted text, keeping trailing punctuation (; . ,) outside the bracket span.
local function prose_brackets(inlines, color)
  local out = pandoc.List()
  local i = 1
  while i <= #inlines do
    local el = inlines[i]
    if el.t == 'Str' and starts(el.text, '[') then
      local j = i
      local found, pre_close, post_punct = false, nil, nil
      while j <= #inlines and j <= i + 45 do
        if inlines[j].t == 'Str' then
          local a, b = inlines[j].text:match('^(.*%])([;,%.]*)$')
          if a then
            found, pre_close, post_punct = true, a, b
            break
          end
        end
        j = j + 1
      end
      if found then
        out:insert(pandoc.RawInline('latex', '{\\mdseries\\scriptsize\\color{tb' .. color .. 'text}'))
        for k = i, j - 1 do out:insert(inlines[k]) end
        out:insert(pandoc.Str(pre_close))
        out:insert(pandoc.RawInline('latex', '}'))
        if post_punct and post_punct ~= '' then out:insert(pandoc.Str(post_punct)) end
        i = j + 1
      else
        out:insert(el)
        i = i + 1
      end
    else
      out:insert(el)
      i = i + 1
    end
  end
  return out
end

local function cell_inlines(cell)
  local blocks = cell.contents
  if #blocks == 0 then return pandoc.List() end
  return pandoc.List(blocks[1].content or {})
end

local function wrap(inlines, pre, post)
  local l = pandoc.List({ pandoc.RawInline('latex', pre) })
  l:extend(inlines)
  l:insert(pandoc.RawInline('latex', post))
  return l
end

local function render(tbl, name, spec)
  local hue = HUE[spec.role] or 'gray'
  if STYLE_MODE == 'B' then
    -- Style B uses raw 4 families + vertical grid lines
    if hue == 'slate' then hue = 'blue' elseif hue == 'stone' then hue = 'gray' end
  end
  local ncol = #tbl.colspecs
  local head = tbl.head.rows[1]
  local rows = pandoc.List()
  for _, body in ipairs(tbl.bodies) do rows:extend(body.body) end

  local htext = {}
  for c = 1, ncol do htext[c] = head and stringify(head.cells[c].contents) or '' end
  local function colmatch(sub)
    for c = 1, ncol do if htext[c]:find(sub, 1, true) then return c end end
  end

  -- alignment: first column and text columns left, numeric columns centered
  local style, align = {}, {}
  for c = 1, ncol do
    local n, k = 0, 0
    for _, r in ipairs(rows) do
      local t = stringify(r.cells[c].contents)
      if t ~= '' then n = n + 1; if numeric(t) then k = k + 1 end end
    end
    align[c] = (c > 1 and n > 0 and k / n >= 0.6) and 'center' or 'left'
    style[c] = (spec.col or {})[htext[c]]
    if style[c] == 'left' or style[c] == 'center' then align[c] = style[c] end
    if style[c] == 'num' then align[c] = 'center' end
  end

  -- column spec: explicit widths from SPEC or pandoc's computed widths
  local cols = {}
  for c, cs in ipairs(tbl.colspecs) do
    local w = spec.widths and spec.widths[c] or cs[2]
    local a = align[c] == 'center' and '\\centering' or '\\raggedright'
    if type(w) == 'number' and w > 0 then
      cols[c] = string.format('>{%s\\arraybackslash}p{(\\linewidth - %d\\tabcolsep) * \\real{%.4f}}', a, 2 * ncol, w)
    else
      cols[c] = align[c] == 'center' and 'c' or 'l'
    end
  end
  local fixed = (spec.widths ~= nil) or (type(tbl.colspecs[1][2]) == 'number' and tbl.colspecs[1][2] > 0)

  local washcol = {}
  for _, sub in ipairs(spec.colwash or {}) do local c = colmatch(sub); if c then washcol[c] = true end end
  local focus_col = spec.focus and colmatch(spec.focus[2])

  -- Pre-check which rows have a top rule so the preceding row can emit \\* (no page break right before a rule)
  local has_rule_above = {}
  for i, r in ipairs(rows) do
    local first = stringify(r.cells[1].contents)
    local band = first_match(spec.band, first)
    local strong_first = (spec.role == 'ledger' or spec.role == 'budget') and #r.cells[1].contents > 0 and
      #cell_inlines(r.cells[1]) == 1 and cell_inlines(r.cells[1])[1].t == 'Strong'
    if strong_first then band = true end
    if i > 1 and (band or first_match(spec.rule, first) or (spec.groups and first ~= '')) then
      has_rule_above[i] = true
    end
  end

  local L = {}
  local function emit(s) L[#L + 1] = s end
  -- TABLES_DEBUG: each wrapped cell is set once more at its column width and its line count logged ("TBCELL name rR cC n")
  local M = {}
  local function measure(r, c, s)
    local w = spec.widths and spec.widths[c] or tbl.colspecs[c][2]
    if not os.getenv('TABLES_DEBUG') or type(w) ~= 'number' or w <= 0 or s == '' then return end
    M[#M + 1] = string.format('\\tbmeasure{%s}{%d}{%d}{%.4f}{%d}{%s %s}', name, r, c, w, 2 * ncol,
      align[c] == 'center' and '\\centering' or '\\raggedright', s)
  end
  emit('\\begingroup\\tbsetup{tb' .. hue .. 'line}')
  local colsep = STYLE_MODE == 'B' and '|' or ''
  local left_edge = STYLE_MODE == 'B' and '|@{\\tbbar\\hskip\\tabcolsep}' or '@{\\tbbar\\hskip\\tabcolsep}'
  local right_edge = STYLE_MODE == 'B' and '@{\\hskip\\tabcolsep}|' or '@{\\hskip\\tabcolsep}'
  emit('\\begin{longtable}[]{' .. left_edge .. table.concat(cols, colsep) .. right_edge .. '}')
  if spec.hero or STYLE_MODE == 'B' then
    emit('\\toprule[1.1pt]\\specialrule{0.35pt}{1.1pt}{0pt}')
  else
    emit('\\toprule[0.9pt]')
  end
  -- header row
  if head then
    local cells = {}
    for c = 1, ncol do
      local s = latex(scripts(cell_inlines(head.cells[c])))
      if s ~= '' then s = '\\textbf{' .. s .. '}' end
      measure(0, c, s)
      if fixed then
        local a = align[c] == 'center' and '\\centering' or '\\raggedright'
        s = '\\begin{minipage}[b]{\\linewidth}' .. a .. ' ' .. s .. '\\end{minipage}'
      end
      cells[c] = s
    end
    cells[1] = '\\tbhstrut ' .. cells[1]
    local hfill = STYLE_MODE == 'B' and ('tb' .. hue .. 'mid') or ('tb' .. hue .. 'fill')
    emit('\\tbclearbar \\rowcolor{' .. hfill .. '}' .. table.concat(cells, ' & ') .. ' \\\\*')
    emit('\\specialrule{0.45pt}{0pt}{0pt}')
  end
  emit('\\endhead')
  emit('\\bottomrule[0.9pt]')
  emit('\\endfoot')

  -- body
  local zebra, group, prevbar = 0, 0, nil
  for i, r in ipairs(rows) do
    local first = stringify(r.cells[1].contents)
    local base = first_match(spec.base, first)
    local rtint = first_match(spec.rowtint, first)
    local band = first_match(spec.band, first)
    local bar = (base and base[2]) or (rtint and rtint[2]) or (first_match(spec.bars, first) or {})[2]
    if first == '' and not spec.groups then bar = prevbar end  -- a blank first cell continues the row above
    prevbar = bar
    local strong_first = (spec.role == 'ledger' or spec.role == 'budget') and #r.cells[1].contents > 0 and
      #cell_inlines(r.cells[1]) == 1 and cell_inlines(r.cells[1])[1].t == 'Strong'
    if strong_first then band = true end
    local pre = {}
    if (band or first_match(spec.rule, first)) and i > 1 then
      pre[#pre + 1] = '\\tbrule{tb' .. hue .. 'mid}{0.42pt}'
    end
    if spec.groups and first ~= '' and i > 1 then
      pre[#pre + 1] = '\\tbrule{tb' .. hue .. 'mid}{0.35pt}'
    end
    pre[#pre + 1] = bar and ('\\tbsetbar{tb' .. bar .. 'line}') or '\\tbclearbar '
    local shaded
    if spec.groups then
      if first ~= '' then group = group + 1 end
      shaded = group % 2 == 0
    else
      zebra = zebra + 1
      shaded = zebra % 2 == 0
    end
    local rowwash = (base or band or rtint) and true or false
    if rtint then
      pre[#pre + 1] = '\\rowcolor{tb' .. rtint[2] .. 'wash}'
    elseif rowwash then
      pre[#pre + 1] = '\\rowcolor{tb' .. hue .. 'wash}'
    elseif shaded then
      local zcol = STYLE_MODE == 'B' and 'tbzebra' or ('tb' .. hue .. 'zebra')
      pre[#pre + 1] = '\\rowcolor{' .. zcol .. '}'
    end
    local cells = {}
    for c = 1, ncol do
      local inl = bold_scripts(cell_inlines(r.cells[c]))
      local tag
      if c == 1 and spec.tags then
        local s = stringify(inl)
        local num, origin = s:match('^(%d+) · (%w+)$')
        if origin and spec.tags[origin] then
          local h = spec.tags[origin]
          tag = num .. ' \\tbtag{tb' .. h .. 'fill}{tb' .. h .. 'line}{tb' .. h .. 'mid}{tb' .. h .. 'text}{' .. origin .. '}'
        end
      end
      if align[c] == 'center' then
        inl = intervals(inl, hue)
      elseif spec.subbrackets and c > 1 then
        inl = prose_brackets(inl, hue)
      end
      local st = style[c]
      if st == 'em' and #inl > 0 then inl = wrap(inl, '\\emph{', '}') end
      if st == 'num' and #inl > 0 then inl = wrap(inl, '\\textcolor{tb' .. hue .. 'text}{\\textbf{', '}}') end
      if (st == 'sc' or (spec.groups and c == 1)) and #inl > 0 then
        inl = wrap(inl, '\\textcolor{tb' .. hue .. 'text}{\\textsc{', '}}')
      end
      local s = tag or latex(inl)
      measure(i, c, s)
      local fill
      if spec.focus and c == focus_col and starts(first, spec.focus[1]) then
        fill = 'tbgoldfill'
      elseif washcol[c] then
        fill = (rowwash or shaded) and ('tb' .. hue .. 'washz') or ('tb' .. hue .. 'wash')
      end
      if fill then s = '\\cellcolor{' .. fill .. '}' .. s end
      cells[c] = s
    end
    -- no page break after the first row, before the last, or immediately before a mid-table rule
    local keep = (#rows >= 4 and (i == 1 or i == #rows - 1)) or has_rule_above[i + 1]
    emit(table.concat(pre, '') .. table.concat(cells, ' & ') .. (keep and ' \\\\*' or ' \\\\'))
  end
  emit('\\end{longtable}')
  emit('\\endgroup')
  if os.getenv('TABLES_DEBUG') then
    io.stderr:write(string.format('table %-8s %-9s %-6s %s\n', name, spec.role, hue, table.concat(align, ',')))
    table.insert(L, 2, '\\providecommand{\\tbmeasure}[6]{{\\dimen0=\\dimexpr\\linewidth-#5\\tabcolsep\\relax' ..
      '\\setbox0\\vbox{\\hsize=#4\\dimen0 \\parindent0pt #6\\par\\xdef\\tbmn{\\the\\prevgraf}}\\typeout{TBCELL #1 r#2 c#3 \\tbmn}}}\n' ..
      table.concat(M, '\n'))
  end
  return pandoc.RawBlock('latex', table.concat(L, '\n'))
end

local function table_name(prev)
  if not prev then return nil end
  if prev.t == 'Para' and prev.content[1] and prev.content[1].t == 'Strong' then
    local label = stringify(prev.content[1])
    local n = label:match('^Table (%S+)%.$')
    if n then return n end
    if label:find('both sides of the budget', 1, true) then return 'summary' end
  elseif prev.t == 'Header' and stringify(prev):find('Dead ends', 1, true) then
    return 'deadends'
  end
end

local function colors()
  local dir = pandoc.path.directory(PANDOC_SCRIPT_FILE)
  return pandoc.pipe('python3', { pandoc.path.join({ dir, 'table_colors.py' }) }, '')
end

function Pandoc(doc)
  if not FORMAT:match('latex') then return nil end
  local out = pandoc.List({ pandoc.RawBlock('latex', colors()) })
  local blocks = doc.blocks
  local names = {}
  for i, b in ipairs(blocks) do
    if b.t == 'Table' then names[i] = table_name(blocks[i - 1]) end
  end
  for i, b in ipairs(blocks) do
    local nextname = names[i + 1]
    if b.t == 'Table' then
      local spec = (names[i] and SPEC[names[i]]) or { role = 'ref' }
      out:insert(render(b, names[i] or '?', spec))
    elseif b.t == 'Para' and nextname then
      local spec = SPEC[nextname] or { role = 'ref' }
      local h = HUE[spec.role] or 'gray'
      b.content:insert(1, pandoc.RawInline('latex', '\\tbmark{tb' .. h .. 'line}{tb' .. h .. 'fill}{tb' .. h .. 'mid}'))
      out:insert(b)
    else
      out:insert(b)
    end
  end
  doc.blocks = out
  return doc
end
